const { withAppBuildGradle } = require('@expo/config-plugins');

const PLUGIN_MARKER = '// @generated by withAndroidReleaseSigning';

const ENVIRONMENT_BLOCK = `${PLUGIN_MARKER}
def craniaReleaseSigningEnvironment = [
    keystorePath: System.getenv("ANDROID_UPLOAD_KEYSTORE"),
    keyAlias: System.getenv("ANDROID_UPLOAD_KEY_ALIAS"),
    storePassword: System.getenv("ANDROID_UPLOAD_STORE_PASSWORD"),
    keyPassword: System.getenv("ANDROID_UPLOAD_KEY_PASSWORD"),
]
def craniaReleaseSigningVariableNames = [
    keystorePath: "ANDROID_UPLOAD_KEYSTORE",
    keyAlias: "ANDROID_UPLOAD_KEY_ALIAS",
    storePassword: "ANDROID_UPLOAD_STORE_PASSWORD",
    keyPassword: "ANDROID_UPLOAD_KEY_PASSWORD",
]
def craniaReleaseSigningMissing = craniaReleaseSigningEnvironment.findAll {
    !it.value?.trim()
}.keySet().collect {
    craniaReleaseSigningVariableNames[it]
}
def craniaReleaseSigningKeystore = craniaReleaseSigningEnvironment.keystorePath
    ? new File(craniaReleaseSigningEnvironment.keystorePath)
    : null
def craniaValidateReleaseSigning = {
    if (!craniaReleaseSigningMissing.isEmpty()) {
        throw new GradleException(
            "Android release signing is not configured. Missing environment variables: " +
            craniaReleaseSigningMissing.join(", ") +
            ". See docs/android-release-signing.md."
        )
    }
    if (!craniaReleaseSigningKeystore.isAbsolute()) {
        throw new GradleException(
            "ANDROID_UPLOAD_KEYSTORE must be an absolute path. " +
            "See docs/android-release-signing.md."
        )
    }
    if (!craniaReleaseSigningKeystore.isFile()) {
        throw new GradleException(
            "ANDROID_UPLOAD_KEYSTORE does not point to a file. " +
            "See docs/android-release-signing.md."
        )
    }
}
def craniaAndroidAppProject = project

gradle.taskGraph.whenReady { taskGraph ->
    def releaseBundleRequested = taskGraph.allTasks.any {
        it.project == craniaAndroidAppProject && it.name == "bundleRelease"
    }
    if (releaseBundleRequested) {
        craniaValidateReleaseSigning()
    }
}
`;

const RELEASE_SIGNING_CONFIG = `
        release {
            if (craniaReleaseSigningMissing.isEmpty()) {
                storeFile craniaReleaseSigningKeystore
                storePassword craniaReleaseSigningEnvironment.storePassword
                keyAlias craniaReleaseSigningEnvironment.keyAlias
                keyPassword craniaReleaseSigningEnvironment.keyPassword
            }
        }
`;

function findBlock(source, blockName, fromIndex = 0) {
    const pattern = new RegExp(`\\b${blockName}\\s*\\{`, 'g');
    pattern.lastIndex = fromIndex;
    const match = pattern.exec(source);

    if (!match) {
        throw new Error(`Unable to find ${blockName} block in android/app/build.gradle`);
    }

    const openBrace = source.indexOf('{', match.index);
    let depth = 0;

    for (let index = openBrace; index < source.length; index += 1) {
        if (source[index] === '{') {
            depth += 1;
        } else if (source[index] === '}') {
            depth -= 1;
            if (depth === 0) {
                return {
                    start: match.index,
                    openBrace,
                    closeBrace: index,
                };
            }
        }
    }

    throw new Error(`Unclosed ${blockName} block in android/app/build.gradle`);
}

function injectAndroidReleaseSigning(source) {
    if (source.includes(PLUGIN_MARKER)) {
        return source;
    }

    const androidBlock = findBlock(source, 'android');
    let updated =
        source.slice(0, androidBlock.start) +
        ENVIRONMENT_BLOCK +
        '\n' +
        source.slice(androidBlock.start);

    const updatedAndroidBlock = findBlock(updated, 'android');
    const signingConfigsBlock = findBlock(
        updated,
        'signingConfigs',
        updatedAndroidBlock.openBrace
    );
    updated =
        updated.slice(0, signingConfigsBlock.closeBrace) +
        RELEASE_SIGNING_CONFIG +
        updated.slice(signingConfigsBlock.closeBrace);

    const buildTypesBlock = findBlock(
        updated,
        'buildTypes',
        signingConfigsBlock.closeBrace + RELEASE_SIGNING_CONFIG.length
    );
    const releaseBlock = findBlock(updated, 'release', buildTypesBlock.openBrace);
    const releaseSource = updated.slice(releaseBlock.start, releaseBlock.closeBrace + 1);
    const debugSigningLine = 'signingConfig signingConfigs.debug';

    if (!releaseSource.includes(debugSigningLine)) {
        throw new Error(
            'Unable to replace the generated debug signingConfig in the release block'
        );
    }

    const releaseWithUploadKey = releaseSource.replace(
        debugSigningLine,
        'signingConfig signingConfigs.release'
    );

    return (
        updated.slice(0, releaseBlock.start) +
        releaseWithUploadKey +
        updated.slice(releaseBlock.closeBrace + 1)
    );
}

function withAndroidReleaseSigning(config) {
    return withAppBuildGradle(config, configWithBuildGradle => {
        if (configWithBuildGradle.modResults.language !== 'groovy') {
            throw new Error('Android release signing requires Groovy build.gradle');
        }

        configWithBuildGradle.modResults.contents = injectAndroidReleaseSigning(
            configWithBuildGradle.modResults.contents
        );
        return configWithBuildGradle;
    });
}

module.exports = withAndroidReleaseSigning;
module.exports.injectAndroidReleaseSigning = injectAndroidReleaseSigning;
module.exports.PLUGIN_MARKER = PLUGIN_MARKER;
